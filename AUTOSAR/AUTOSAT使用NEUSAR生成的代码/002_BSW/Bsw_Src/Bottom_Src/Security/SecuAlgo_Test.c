static void test_secuboot(void) {
    verifyCodeSegments verSeg = { 0 };
    hostSecureBootTag0_t* verSign[8] = { NULL_PTR };
    xoscClkCofigData_t xoscConfigData = { 0 };
    uint8 i;
    uint32 cmacLen;

    Secu_Memset((uint8*) &verSeg, 0, sizeof(verSeg));
    Secu_Memset((uint8*) &xoscConfigData, 0, sizeof(xoscConfigData));

    verSeg.seg[0].address = (uint32) 0xFC8000;
    verSeg.seg[0].length = 32 * 1024;
    verSeg.seg[1].address = (uint32) 0x01000000;
    verSeg.seg[1].length = 64 * 1024;

    verSign[0] = (hostSecureBootTag0_t *) secuboot_boot_cmac;
    verSign[1] = (hostSecureBootTag0_t *) secuboot_app_cmac;

    test_ret = Crypto_AutoSar_Ext_ConfigSecureBoot(
        HSM_SECURE_BOOT_TYPE_STRICT,
        6, // NVM SYM 6
        HSM_SECURE_BOOT_ONFAIL_DEGRADE,
        NULL_PTR,
        &verSeg,
        (codeSigns0 *) verSign,
        2,
        TRUE, FALSE, FALSE
    );

    for (i = 0; i < 4; i++) {
        if (verSeg.seg[i].length == 0) {
            break;
        }

        cmacLen = 16;
        SecuAuth_Calculate_AesCmacGenerate(
            6, SECU_OPERATIONMODE_SINGLECALL, (uint8*) verSeg.seg[i].address, verSeg.seg[i].length, &output_data64[i*16], &cmacLen
        );
    }
}


static void prepare_import_key(void) {
    volatile Std_ReturnType ret = E_NOT_OK;

    HSM_LLD_GetKeyInfo(SecuUtils_GetKeyHandle(HSM_AUTH_KEY_ID), &key_info);
    if (key_info.keyBitLen == 0) {
        ret = Secu_KeyElementSet(HSM_AUTH_KEY_ID, SECU_KE_CIPHER_KEY, (uint8 *) HSM_Internal_KEY_AUTH, sizeof(HSM_Internal_KEY_AUTH));
    }

    SecuAlgo_Init();
}


